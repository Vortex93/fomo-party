type GameID string

const (
	SameBrain  GameID = "same-brain"
	WhosLying  GameID = "whos-lying"
	DrawGuess  GameID = "draw-guess"
	MostLikely GameID = "most-likely"
	Memory     GameID = "memory-clash"
	MaxPlayers        = 15
)

type GameInfo struct {
	ID          GameID `json:"id"`
	Name        string `json:"name"`
	MinPlayers  int    `json:"minPlayers"`
	Description string `json:"description"`
}

var Catalog = []GameInfo{
	{SameBrain, "Same Brain", 3, "Think alike. Matching the biggest answer group earns points."},
	{WhosLying, "Who's Lying?", 4, "One player has no question. Spot their believable bluff."},
	{DrawGuess, "Draw & Guess", 2, "One phone becomes a sketchpad. Everyone else guesses."},
	{MostLikely, "Most Likely To", 3, "Make a kind nomination. Match the group's top pick."},
	{Memory, "Memory Clash", 2, "Remember the symbols, then tap them in the same order."},
}

type Config struct {
	Games   []GameID `json:"games"`
	Rounds  int      `json:"rounds"`
	Seconds int      `json:"seconds"`
}

func DefaultConfig() Config {
	return Config{[]GameID{SameBrain, WhosLying, DrawGuess, MostLikely, Memory}, 2, 40}
}

func (c Config) Validate() error {
	if len(c.Games) < 1 || len(c.Games) > len(Catalog) {
		return errors.New("Choose between one and five games.")
	}
	if c.Rounds < 1 || c.Rounds > 5 || c.Seconds < 20 || c.Seconds > 90 {
		return errors.New("Choose 1–5 rounds per game and a 20–90 second timer.")
	}
	seen := map[GameID]bool{}
	for _, id := range c.Games {
		known := false
		for _, info := range Catalog {
			if id == info.ID {
				known = true
			}
		}
		if !known || seen[id] {
			return errors.New("The playlist contains an unknown or repeated game.")
		}
		seen[id] = true
	}
	return nil
}

func (c Config) Minimum() int {
	n := 2
	for _, id := range c.Games {
		for _, info := range Catalog {
			if info.ID == id && info.MinPlayers > n {
				n = info.MinPlayers
			}
		}
	}
	return n
}

