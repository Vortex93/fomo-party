// Token is generated by the operating system's cryptographically secure RNG.
func Token(bytes int) string {
	b := make([]byte, bytes)
	if _, err := rand.Read(b); err != nil {
		panic("secure randomness unavailable: " + err.Error())
	}
	return hex.EncodeToString(b)
}

func randomN(n int) int {
	v, err := rand.Int(rand.Reader, big.NewInt(int64(n)))
	if err != nil {
		panic("secure randomness unavailable: " + err.Error())
	}
	return int(v.Int64())
}

func NewRoom(code, name string, now time.Time) (*Room, *Player, error) {
	r := &Room{
		Code: code, Status: "lobby", Config: DefaultConfig(), Cursor: -1,
		CreatedAt: now, LastActivity: now, UsedPrompts: map[GameID]map[int]bool{},
	}
	p, err := r.Join(name, now)
	if err != nil {
		return nil, nil, err
	}
	p.Ready = true
	r.HostID = p.ID
	return r, p, nil
}

func cleanText(text string, max int) (string, error) {
	if !utf8.ValidString(text) {
		return "", errors.New("Use valid text.")
	}
	text = strings.TrimSpace(text)
	if text == "" || utf8.RuneCountInString(text) > max {
		return "", fmt.Errorf("Enter 1–%d characters.", max)
	}
	for _, r := range text {
		if unicode.IsControl(r) || unicode.In(r, unicode.Cf) {
			return "", errors.New("Please use ordinary text without control characters.")
		}
	}
	return text, nil
}

// Normalize is deliberately predictable, not fuzzy: ignore case, punctuation,
// and repeated whitespace. Accents and different spellings remain significant.
func Normalize(text string) string {
	text = strings.Map(func(r rune) rune {
		if unicode.IsLetter(r) || unicode.IsNumber(r) {
			return unicode.ToLower(r)
		}
		return ' '
	}, text)
	return strings.Join(strings.Fields(text), " ")
}

func (r *Room) Player(id string) *Player {
	for _, p := range r.Players {
		if p.ID == id {
			return p
		}
	}
	return nil
}

func (r *Room) Join(name string, now time.Time) (*Player, error) {
	if r.Status != "lobby" {
		return nil, errors.New("This game has started. Watch it, or join the next lobby.")
	}
	if len(r.Players) >= MaxPlayers {
		return nil, errors.New("This room already has 15 players.")
	}
	name, err := cleanText(name, 20)
	if err != nil {
		return nil, err
	}
	if Normalize(name) == "" {
		return nil, errors.New("Include at least one letter or number in your name.")
	}
	for _, p := range r.Players {
		if Normalize(p.Name) == Normalize(name) {
			return nil, errors.New("That name is taken. Add an initial or choose another.")
		}
	}
	p := &Player{ID: Token(8), Token: Token(32), Name: name, LastSeen: now}
	r.Players = append(r.Players, p)
	r.LastActivity = now
	return p, nil
}

func (r *Room) Connected(id string, connected bool, now time.Time) {
	if p := r.Player(id); p != nil {
		p.Connected = connected
		p.LastSeen = now
		r.LastActivity = now
	}
}

func contains(ids []string, id string) bool {
	for _, v := range ids {
		if v == id {
			return true
		}
	}
	return false
}
